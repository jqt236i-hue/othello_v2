const fs = require('fs');
const path = require('path');
const Module = require('module');
const root = process.cwd();
const fixture = JSON.parse(fs.readFileSync(path.join(root,'tmp','nonstandard-case-seed1-ply56.json'),'utf8'));
const filename = path.join(root, 'src', 'engine', 'selfplay-runner.js');
let code = fs.readFileSync(filename, 'utf8');
code += `\nmodule.exports.__internal = { buildMovePlanContext, getDirectUsableCardIds };`;
const m = new Module(filename, module);
m.filename = filename;
m.paths = Module._nodeModulePaths(path.dirname(filename));
m._compile(code, filename);
const { buildMovePlanContext, getDirectUsableCardIds } = m.exports.__internal;
const CpuPolicyCore = require(path.join(root,'game','ai','cpu-policy-core.js'));
const usable = getDirectUsableCardIds(fixture.cardState, fixture.gameState, fixture.playerKey);
const movePlanContext = buildMovePlanContext(fixture.gameState, fixture.cardState, fixture.playerKey, fixture.legalMoves, usable);
const scores = fixture.legalMoves.map(m => ({ row:m.row, col:m.col, score: movePlanContext ? Number(CpuPolicyCore.scoreMoveForCornerEdgePlan(m, movePlanContext) || 0) : null }));
console.log(JSON.stringify({ usable, hasMovePlanContext: !!movePlanContext, movePlanContext, scores }, null, 2));
