const fs = require('fs');
const path = require('path');
const Module = require('module');
const root = process.cwd();
const fixture = JSON.parse(fs.readFileSync(path.join(root,'tmp','nonstandard-case-seed1-ply56.json'),'utf8'));
const filename = path.join(root, 'src', 'engine', 'selfplay-runner.js');
let code = fs.readFileSync(filename, 'utf8');
code += `\nmodule.exports.__internal = { choosePlacementMoveByBrowserParity, buildMovePlanContext, getDirectUsableCardIds };`;
const m = new Module(filename, module);
m.filename = filename;
m.paths = Module._nodeModulePaths(path.dirname(filename));
m._compile(code, filename);
const { choosePlacementMoveByBrowserParity, buildMovePlanContext, getDirectUsableCardIds } = m.exports.__internal;
const usable = getDirectUsableCardIds(fixture.cardState, fixture.gameState, fixture.playerKey);
const movePlanContext = buildMovePlanContext(fixture.gameState, fixture.cardState, fixture.playerKey, fixture.legalMoves, usable);
const parity = choosePlacementMoveByBrowserParity(fixture.legalMoves,{gameState:fixture.gameState,cardState:fixture.cardState,playerKey:fixture.playerKey,pendingType:null},{enableTacticalLookahead:false}, movePlanContext);
const scores = fixture.legalMoves.map(m => ({ row:m.row, col:m.col, combined: parity.combinedScoreFn(m), movePlan: parity.movePlanScoreFn ? parity.movePlanScoreFn(m) : null }));
console.log(JSON.stringify({ hasMovePlanContext: !!movePlanContext, parityMove: parity.move, scores }, null, 2));
